  public async createReminderFromLead(leadData: any, reminderType: 'followup' | 'call' | 'meeting' = 'followup') {
    if (!this.centreId) {
      console.error('❌ ReminderService: Cannot create reminder - no centreId');
      return;
    }

    try {
      // Determine the due date based on lead data
      let dueDate: Date;
      let title: string;
      let description: string;

      if (reminderType === 'followup' && leadData.followUpDate) {
        dueDate = new Date(leadData.followUpDate);
        title = `Follow-up: ${leadData.name}`;
        description = `Follow-up call for ${leadData.name} - ${leadData.interestedCourse}`;
      } else if (reminderType === 'call') {
        // Default to 24 hours from now for call reminders
        dueDate = new Date(Date.now() + 24 * 60 * 60 * 1000);
        title = `Call: ${leadData.name}`;
        description = `Initial call to ${leadData.name} - ${leadData.interestedCourse}`;
      } else {
        // Default to 48 hours from now for meeting reminders
        dueDate = new Date(Date.now() + 48 * 60 * 60 * 1000);
        title = `Meeting: ${leadData.name}`;
        description = `Schedule meeting with ${leadData.name} - ${leadData.interestedCourse}`;
      }

      const reminderData = {
        leadId: leadData.id,
        leadName: leadData.name,
        leadPhone: leadData.phone,
        leadEmail: leadData.email,
        title,
        description,
        dueDate: Timestamp.fromDate(dueDate),
        status: "pending" as const,
        priority: "medium" as const,
        type: reminderType as const,
        notes: `Auto-generated from lead: ${leadData.notes || ''}`,
        assignedTo: leadData.assignedTo || 'unassigned',
        centreId: this.centreId,
        createdBy: leadData.createdBy || 'system',
        createdAt: Timestamp.now(),
        updatedAt: Timestamp.now(),
        autoGenerated: true
      };

      const docRef = await addDoc(collection(db, 'reminders'), reminderData);
      
      return docRef.id;
    } catch (error) {
      console.error('❌ Error creating auto-reminder for lead:', error);
      throw error;
    }
  }

  public async updateReminderFromLead(leadData: any, existingReminderId?: string) {
    if (!this.centreId) {
      console.error('❌ ReminderService: Cannot update reminder - no centreId');
      return;
    }

    try {
      // If we have a follow-up date, update or create reminder
      if (leadData.followUpDate) {
        const dueDate = new Date(leadData.followUpDate);
        const title = `Follow-up: ${leadData.name}`;
        const description = `Follow-up call for ${leadData.name} - ${leadData.interestedCourse}`;

        const reminderData = {
          leadId: leadData.id,
          leadName: leadData.name,
          leadPhone: leadData.phone,
          leadEmail: leadData.email,
          title,
          description,
          dueDate: Timestamp.fromDate(dueDate),
          status: "pending" as const,
          priority: "medium" as const,
          type: "followup" as const,
          notes: `Updated from lead: ${leadData.notes || ''}`,
          assignedTo: leadData.assignedTo || 'unassigned',
          centreId: this.centreId,
          updatedBy: leadData.updatedBy || 'system',
          updatedAt: Timestamp.now(),
          autoGenerated: true
        };

        if (existingReminderId) {
          // Update existing reminder
          const reminderRef = doc(db, 'reminders', existingReminderId);
          await updateDoc(reminderRef, reminderData);
          return existingReminderId;
        } else {
          // Create new reminder
          reminderData.createdBy = leadData.updatedBy || 'system';
          reminderData.createdAt = Timestamp.now();
          const docRef = await addDoc(collection(db, 'reminders'), reminderData);
          return docRef.id;
        }
      }
    } catch (error) {
      console.error('❌ Error updating auto-reminder for lead:', error);
      throw error;
    }
  }

  public async deleteRemindersForLead(leadId: string) {
    if (!this.centreId) {
      console.error('❌ ReminderService: Cannot delete reminders - no centreId');
      return;
    }

    try {
      const remindersRef = collection(db, 'reminders');
      const q = query(
        remindersRef,
        where('centreId', '==', this.centreId),
        where('leadId', '==', leadId)
      );
      
      const querySnapshot = await getDocs(q);
      const deletePromises = querySnapshot.docs.map(doc => deleteDoc(doc.ref));
      
      await Promise.all(deletePromises);
    } catch (error) {
      console.error('❌ Error deleting reminders for lead:', error);
      throw error;
    }
  }

  public async createReminder(reminderData: any) {
    if (!this.centreId) {
      console.error('❌ ReminderService: Cannot create reminder - no centreId');
      return;
    }

    try {
      const docRef = await addDoc(collection(db, 'reminders'), reminderData);
      return docRef.id;
    } catch (error) {
      console.error('❌ Error creating reminder:', error);
      throw error;
    }
  }

  public async updateReminder(reminderId: string, updateData: any) {
    try {
      const reminderRef = doc(db, 'reminders', reminderId);
      await updateDoc(reminderRef, updateData);
    } catch (error) {
      console.error('❌ Error updating reminder:', error);
      throw error;
    }
  }

  public async deleteReminder(reminderId: string) {
    try {
      const reminderRef = doc(db, 'reminders', reminderId);
      await deleteDoc(reminderRef);
    } catch (error) {
      console.error('❌ Error deleting reminder:', error);
      throw error;
    }
  }

  public getStatus() {
    return {
      isInitialized: this.isInitialized,
      centreId: this.centreId,
      hasReminderListener: !!this.unsubscribeFromReminders,
      remindersCount: this.reminders.size,
      activeNotificationsCount: this.activeNotifications.size,
      scheduledTimeoutsCount: this.scheduledTimeouts.size,
      hasCheckInterval: !!this.checkInterval
    };
  }

  public getActiveNotifications() {
    return Array.from(this.activeNotifications.values());
  }

